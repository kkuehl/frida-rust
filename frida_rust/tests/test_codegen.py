class CliTest(unittest.TestCase):
    def run_cli(self, unix: bytes, windows: bytes, rustfmt: str):
        with tempfile.TemporaryDirectory() as tmp:
            tmp = Path(tmp)
            girs = write_girs(tmp, unix, windows)
            out = tmp / "out"
            stdout, stderr = io.StringIO(), io.StringIO()
            with contextlib.redirect_stdout(stdout), contextlib.redirect_stderr(stderr):
                code = cli.main([
                    "--gir", str(girs["unix"]), "--windows-gir", str(girs["windows"]),
                    "--glib-gir", str(girs["glib"]), "--gobject-gir", str(girs["gobject"]),
                    "--gio-gir", str(girs["gio"]),
                    "--output", str(out), "--frida-version", "1.2.3", "--rustfmt", rustfmt,
                ])
            files = sorted(p.name for p in out.glob("*.rs")) if out.exists() else []
            return code, stdout.getvalue(), stderr.getvalue(), files

    def test_an_unsupported_construct_exits_non_zero_and_writes_nothing(self):
        bad = gir(method("take", b'<type name="GLib.PtrArray" c:type="GPtrArray*" />'))
        code, stdout, stderr, files = self.run_cli(bad, bad, rustfmt="rustfmt")
        self.assertEqual(code, 1)
        self.assertIn("FAILED (1)", stdout)
        self.assertIn("Frida.Odd.take", stdout)
        self.assertEqual(files, [])

    def test_a_construct_the_loader_refuses_exits_non_zero(self):
        bad = gir(b'<constant name="ANSWER" value="42" c:type="FRIDA_ANSWER"><type name="gint"/></constant>')
        code, _, stderr, files = self.run_cli(bad, bad, rustfmt="rustfmt")
        self.assertEqual(code, 1)
        self.assertIn("unknown element <constant>", stderr)
        self.assertEqual(files, [])

    @unittest.skipUnless(shutil.which("rustfmt"), "needs rustfmt")
    def test_a_good_gir_is_written_and_counted(self):
        good = gir(handle_thing())
        with tables(**THING_TABLES):
            code, stdout, _, files = self.run_cli(good, good, rustfmt=shutil.which("rustfmt"))
        self.assertEqual(code, 0, stdout)
