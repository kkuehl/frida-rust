class ValueTest(unittest.TestCase):
    def generate_options(self, **extra):
        collections = {"Frida.TweakOptions.add_tag": ("tags", None)}
        with tables(VALUE_COLLECTIONS=collections, **extra):
            report, files = generate(OPTIONS)
        self.assertEqual(report.failures, [])
        self.assertEqual(report.stale_skips, [])
        return report, files["tweak_options.rs"]

    def test_a_class_with_writable_properties_is_a_value(self):
        _, code = self.generate_options()
        self.assertIn("#[derive(Debug, Clone, PartialEq)]\n#[non_exhaustive]\npub struct TweakOptions {", code)
        self.assertIn("pub name: Option<String>,", code)
        # No default in the GIR: unset, leaving frida-core's.
        self.assertIn("pub depth: Option<u32>,", code)
        # A default in the GIR: the plain type, starting at it.
        self.assertIn("pub wait: i32,", code)
        self.assertIn("wait: 0,", code)
        self.assertIn("pub tags: Vec<String>,", code)
        self.assertNotIn("object_type!", code)
        self.assertNotIn("unsafe impl Send", code, "a value is Send and Sync on its own")

    def test_a_value_is_built_in_one_expression(self):
        _, code = self.generate_options()
        self.assertIn("pub fn name(mut self, name: impl Into<String>) -> Self {", code)
        self.assertIn("pub fn add_tag(mut self, tag: impl Into<String>) -> Self {", code)
        self.assertIn("impl Default for TweakOptions", code)

    def test_a_value_becomes_a_fresh_object_for_each_call(self):
        _, code = self.generate_options()
        self.assertIn("pub fn to_object(&self) -> Result<crate::gir::Object, crate::gir::Error>", code)
        self.assertIn("frida_sys::frida_tweak_options_new()", code)
        self.assertIn("if let Some(value) = &self.name {", code)
        self.assertIn("let value_raw = crate::gir::marshal::cstring(value)?;", code)
        self.assertIn("for item in &self.tags {", code)
        self.assertIn("frida_sys::frida_tweak_options_add_tag(raw.cast(), arg0.as_ptr())", code)

    def test_a_boundary_type_shapes_the_field(self):
        _, code = self.generate_options(BOUNDARY_TYPES={"Frida.TweakOptions:wait": "timeout-ms"})
        self.assertIn("pub wait: Option<std::time::Duration>,", code)
        self.assertIn("wait: Some(std::time::Duration::from_millis(0)),", code)
        self.assertIn("crate::gir::marshal::timeout_ms(*value)?", code)

    def test_a_collection_not_in_the_table_is_refused(self):
        report, _ = generate(OPTIONS)
        self.assertIn("Frida.TweakOptions.add_tag", [e.path for e in report.failures])

    def test_a_method_taking_a_value_converts_it(self):
        # The Odd class's method is plain; list it as safe and pass the value.
        with tables(THREAD_SAFE_METHODS={"Frida.Odd.tweak": "x"},
                    VALUE_COLLECTIONS={"Frida.TweakOptions.add_tag": ("tags", None)}):
            report, files = generate(
                OPTIONS, method("tweak", b'<type name="Frida.TweakOptions" c:type="FridaTweakOptions*" />')
            )
        self.assertEqual(report.failures, [])
        code = files["odd.rs"]
        self.assertIn("value: &crate::gir::TweakOptions", code)
        self.assertIn("let value_raw = value.to_object()?;", code)
        self.assertIn("-> Result<(), crate::gir::Error>", code)


