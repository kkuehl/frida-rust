# The real tables name frida-core's classes, which the fragments here lack; each test
# that wants entries patches them in.
_EMPTY_TABLES = [
    mock.patch.dict(table, {}, clear=True)
    for table in (
        customization.THREAD_SAFE_METHODS, customization.ON_FRIDA_THREAD,
        customization.MUTABLE_GETTERS, customization.IMMUTABLE, customization.EXTENSIONS,
        customization.OWNERS, customization.BOUNDARY_TYPES, customization.VALUE_COLLECTIONS,
        customization.MEMBER_RENAMES, customization.ALLOWS, customization.NOT_VALUES,
        customization.SKIPS, customization.EXAMPLES,
    )
]

# What a handle Thing needs: its getter reads immutable state, get_names is safe.
THING_TABLES = {
    "IMMUTABLE": {"Frida.Thing": "test"},
    "THREAD_SAFE_METHODS": {"Frida.Thing.get_names": "test"},
}


def tables(**entries):
    """Patches the named customization tables with `entries` for a `with` block."""
    stack = contextlib.ExitStack()
    for name, values in entries.items():
        stack.enter_context(mock.patch.dict(getattr(customization, name), values))
    return stack


def setUpModule():
    for patch in _EMPTY_TABLES:
        patch.start()


def tearDownModule():
    for patch in reversed(_EMPTY_TABLES):
        patch.stop()


def generate(*parts: bytes, windows_parts=None):
    model = load(gir(*parts), gir(*(windows_parts if windows_parts is not None else parts)))
    generator = Generator(model, "1.2.3")
    files = generator.generate()
    return generator.report, files


class GenerateTest(unittest.TestCase):
    def setUp(self):
        with tables(**THING_TABLES):
            self.report, self.files = generate(handle_thing(), UNIX_ONLY, windows_parts=[handle_thing()])

    def test_files(self):
        self.assertEqual(sorted(self.files), ["enums.rs", "functions.rs", "mod.rs", "thing.rs"])
        for name, text in self.files.items():
            self.assertTrue(
                text.startswith("// Generated by frida_rust from frida-core.gir of Frida 1.2.3."),
                name,
            )

    def test_counts(self):
        r = self.report
        self.assertEqual(r.failures, [])
        self.assertEqual((r.count("class"), r.count("class", "generated")), (1, 1))
        self.assertEqual((r.count("constructor"), r.count("constructor", "generated")), (1, 1))
        # get_label, get_names and the core's async poke are generated; poke_finish and
        # poke_sync, the forms poke stands for, are counted as skipped with their reasons.
        self.assertEqual((r.count("method"), r.count("method", "generated")), (5, 3))
        self.assertEqual(r.count("method", "skipped"), 2)
        generated = {e.path: e.item for e in r.entries if e.status == "generated" and e.category == "method"}
        self.assertTrue(generated["Frida.Thing.poke"].is_async)
        self.assertEqual((r.count("property"), r.count("property", "generated")), (1, 1))
        self.assertEqual((r.count("signal"), r.count("signal", "generated")), (1, 1))
        self.assertEqual((r.count("enumeration"), r.count("enumeration", "generated")), (3, 3))

    def test_sync_form_takes_the_plain_name(self):
        thing = self.files["thing.rs"]
        self.assertIn("pub fn poke(", thing)
        self.assertNotIn("pub fn poke_sync(", thing)
        self.assertIn("frida_sys::frida_thing_poke_sync(", thing)
        self.assertIn("cancellable: Option<&crate::gir::Cancellable>", thing)
        self.assertIn("-> Result<crate::gir::Kind, crate::gir::Error>", thing)

    def test_an_async_method_without_its_sync_form_fails(self):
        fragment = handle_thing()
        start = fragment.index(b'<method name="poke_sync"')
        end = fragment.index(b"</method>", start) + len(b"</method>")
        with tables(**THING_TABLES):
            report, _ = generate(fragment[:start] + fragment[end:])
        self.assertEqual(
            [(e.path, e.reason) for e in report.failures],
            [("Frida.Thing.poke", "an async method with no `poke_sync` form to call")],
        )

    def test_an_async_method_whose_sync_form_disagrees_fails(self):
        fragment = handle_thing()
        start = fragment.index(b'<method name="poke_sync"')
        fragment = fragment[:start] + fragment[start:].replace(b' throws="1"', b"", 1)
        with tables(**THING_TABLES):
            report, _ = generate(fragment)
        self.assertEqual([e.path for e in report.failures], ["Frida.Thing.poke"])
        self.assertIn("disagrees with the core's view", report.failures[0].reason)

    def test_properties_become_their_accessors(self):
        thing = self.files["thing.rs"]
        self.assertIn("#[must_use]\npub fn label(&self) -> Option<String>", thing)
        # A method that is not a property accessor keeps its name.
        self.assertIn("pub fn get_names(&self) -> Vec<String>", thing)

    def test_a_handle_is_send_and_sync_and_prints_its_properties(self):
        thing = self.files["thing.rs"]
        self.assertIn("unsafe impl Send for Thing {}", thing)
        self.assertIn("unsafe impl Sync for Thing {}", thing)
        self.assertIn('f.debug_struct("Thing").field("label", &self.label()).finish()', thing)

    def test_no_file_switches_lints_off(self):
        for name, text in self.files.items():
            self.assertNotIn("#![allow", text, name)
            self.assertNotIn("panic!", text, name)
            self.assertNotIn(".unwrap()", text, name)

    def test_ownership(self):
        thing = self.files["thing.rs"]
        # transfer none: copied, not freed. transfer full: freed after the copy.
        self.assertIn("marshal::string(raw_ret, false)", thing)
        self.assertIn("marshal::string_array(raw_ret, raw_ret_length, true)", thing)
        self.assertIn("ObjectType>::from_glib_full(raw_ret.cast())", thing)

    def test_platform_cfg(self):
        enums = self.files["enums.rs"]
        before_wait_kind = enums[: enums.index("pub enum WaitKind")]
        self.assertTrue(before_wait_kind.rstrip().endswith("#[non_exhaustive]"))
        self.assertIn("#[cfg(not(windows))]\n#[derive", enums)
        # The enum, its impl, two From impls, Display and FromStr.
        self.assertEqual(enums.count("#[cfg(not(windows))]"), 6)

    def test_error_domain_is_error_kind(self):
        enums = self.files["enums.rs"]
        self.assertIn("pub enum ErrorKind", enums)
        self.assertIn("10 => Self::NotSupported,", enums)
        self.assertIn("_ => Self::Other,", enums)
        for extra in ("Cancelled", "Rpc", "Unexpected", "Other"):
            self.assertIn(f"\n{extra},\n", enums)
        self.assertIn('Self::NotSupported => "not supported",', enums)
        self.assertNotIn("ErrorKind::from_raw", enums)

    def test_enumerations_display_and_parse_their_nick(self):
        enums = self.files["enums.rs"]
        self.assertIn("other => Self::Unknown(i64::from(other)),", enums)
        self.assertIn('Self::Gentle => "gentle",', enums)
        self.assertIn('"firm" => Ok(Self::Firm),', enums)
        self.assertIn("impl std::str::FromStr for Kind", enums)


class UnsupportedTest(unittest.TestCase):
    def assertFails(self, fragment: bytes, path: str, reason: str):
        with tables(THREAD_SAFE_METHODS={path: "test"}):
            report, _ = generate(fragment)
        failures = {(f.path, f.reason) for f in report.failures}
        self.assertTrue(any(p == path and reason in r for p, r in failures), failures)

    def test_unknown_argument_type(self):
        self.assertFails(
            method("take", b'<type name="glong" c:type="glong" />'),
            "Frida.Odd.take",
            "no rule for type glong",
        )

    def test_a_type_the_core_cannot_read(self):
        # The core raises on the class's methods, so each fails with its reason.
        self.assertFails(
            method("take", b'<type name="GLib.PtrArray" c:type="GPtrArray*" />'),
            "Frida.Odd.take",
            "frida_bindgen_core: unable to resolve type PtrArray",
        )

    def test_transfer_full_argument(self):
        self.assertFails(
            method("take", b'<type name="utf8" c:type="gchar*" />', b"full"),
            "Frida.Odd.take",
            "transfer-ownership=full on an argument",
        )

    def test_container_transfer(self):
        fragment = handle_thing().replace(
            b'<return-value transfer-ownership="full">\n          <array',
            b'<return-value transfer-ownership="container">\n          <array',
        )
        with tables(**THING_TABLES):
            self.assertFails(fragment, "Frida.Thing.get_names", "transfer-ownership=container")

    def test_untyped_callback_data(self):
        self.assertFails(
            method("each", b'<type name="GLib.Func" c:type="GFunc" />').replace(
                b'<parameter name="value" transfer-ownership="none">',
                b'<parameter name="value" transfer-ownership="none" closure="1" scope="call">',
            ).replace(
                b"</parameter>\n        </parameters>",
                b'</parameter>\n          <parameter name="value_target" transfer-ownership="none" nullable="1">'
                b'<type name="gpointer" c:type="void*" /></parameter>\n        </parameters>',
            ),
            "Frida.Odd.each",
            "untyped gpointer",
        )

    def test_hash_table_of_other_types(self):
        self.assertFails(
            method(
                "take",
                b'<type name="GLib.HashTable" c:type="GHashTable*"><type name="utf8" c:type="gchar*"/>'
                b'<type name="gint" c:type="gint"/></type>',
            ),
            "Frida.Odd.take",
            "only GHashTable<string, Variant> is supported",
        )

    def test_a_skip_table_entry_turns_a_failure_into_a_skip(self):
        fragment = method("take", b'<type name="GLib.PtrArray" c:type="GPtrArray*" />')
        with mock.patch.dict(customization.SKIPS, {"Frida.Odd.take": "no reason"}):
            report, _ = generate(fragment)
        self.assertEqual(report.failures, [])
        self.assertEqual(report.count("method", "skipped"), 1)
        self.assertEqual(report.stale_skips, [])

    def test_a_stale_skip_table_entry_is_reported(self):
        with tables(**THING_TABLES), mock.patch.dict(customization.SKIPS, {"Frida.Thing.get_names": "skip"}):
            report, _ = generate(handle_thing())
        self.assertEqual(report.count("method", "skipped"), 3)
        with tables(**THING_TABLES), mock.patch.dict(customization.SKIPS, {"Frida.Gone.method": "gone"}):
            report, _ = generate(handle_thing())
        self.assertEqual(report.stale_skips, ["Frida.Gone.method"])

    def test_a_plain_method_nobody_classified_is_refused(self):
        with tables(IMMUTABLE={"Frida.Thing": "test"}):
            report, _ = generate(handle_thing())
        self.assertEqual([e.path for e in report.failures], ["Frida.Thing.get_names"])
        self.assertIn("THREAD_SAFE_METHODS nor ON_FRIDA_THREAD", report.failures[0].reason)

    def test_a_getter_of_a_class_not_known_to_be_immutable_is_refused(self):
        with tables(THREAD_SAFE_METHODS={"Frida.Thing.get_names": "test"}):
            report, _ = generate(handle_thing())
        self.assertIn("Frida.Thing.get_label", [e.path for e in report.failures])


class SignalTest(unittest.TestCase):
    def test_a_signal_becomes_a_connect_method_taking_a_send_closure(self):
        with tables(**THING_TABLES):
            report, files = generate(handle_thing())
        self.assertEqual(report.failures, [])
        thing = files["thing.rs"]
        self.assertIn(
            "pub fn connect_poked<F: FnMut(crate::gir::Kind) + Send + 'static>(&self, handler: F)"
            " -> crate::gir::SignalHandler",
            thing,
        )
        self.assertIn('c"poked"', thing)
        self.assertIn("crate::gir::Kind::from_raw(how)", thing)
        self.assertIn("crate::gir::signal::emit::<F>", thing)

    def test_arguments_are_borrowed(self):
        cases = {
            b'<type name="utf8" c:type="gchar*" />': ("&str", "str_arg(what).unwrap_or_default()"),
            b'<type name="GLib.Bytes" c:type="GBytes*" />': ("&[u8]", "bytes_arg(what)"),
            b'<type name="guint" c:type="guint" />': ("u32", None),
            b'<type name="GLib.Variant" c:type="GVariant*" />': ("&crate::Variant", "variant(what, false)"),
            b'<type name="Gio.SocketAddress" c:type="GSocketAddress*" />': (
                "&crate::gir::SocketAddress", "runtime::borrow::<crate::gir::SocketAddress>",
            ),
        }
        for arg, (rust, conversion) in cases.items():
            report, files = generate(emitter(arg))
            self.assertEqual(report.failures, [], arg)
            code = files["emitter.rs"]
            self.assertIn(f"pub fn connect_went_off<F: FnMut({rust}) + Send + 'static>", code)
            self.assertIn('c"went-off"', code)
            if conversion:
                self.assertIn(conversion, code)
            self.assertNotIn("from_glib_full", code, "nothing a signal lends is taken over")

    def test_a_value_is_not_lent_to_a_handler(self):
        # A Thing with a writable property is a value, which no signal can pass.
        report, _ = generate(THING, emitter(b'<type name="Frida.Thing" c:type="FridaThing*" />'))
        self.assertIn("Frida.Emitter::went-off", [e.path for e in report.failures])

    def test_a_non_null_object_that_arrives_null_is_not_delivered(self):
        report, files = generate(emitter(b'<type name="Gio.SocketAddress" c:type="GSocketAddress*" />'))
        self.assertEqual(report.failures, [])
        self.assertIn("else {\nreturn;\n};", files["emitter.rs"])

    def test_an_argument_handed_over_is_refused(self):
        fragment = emitter(b'<type name="utf8" c:type="gchar*" />').replace(
            b'name="what" transfer-ownership="none"', b'name="what" transfer-ownership="full"'
        )
        report, _ = generate(fragment)
        self.assertEqual([e.path for e in report.failures], ["Frida.Emitter::went-off"])


