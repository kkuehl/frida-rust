class DocsTest(unittest.TestCase):
    @staticmethod
    def resolve(kind, target):
        return f"[`{target.split('.')[-1]}`](crate::gir::{target.split('.')[-1]})"

    def test_links_constants_and_parameters(self):
        lines = to_rustdoc("Pass it to [class@Frida.Device] when @flag is %TRUE; see a[0].", self.resolve)
        self.assertEqual(
            lines, ["Pass it to [`Device`](crate::gir::Device) when `flag` is `true`; see a\\[0\\]."]
        )

    def test_code_never_becomes_a_doctest(self):
        lines = to_rustdoc("Example:\n\n1. Defaults:\n{\n    \"port\": 1\n}\n\nDone.", self.resolve)
        self.assertEqual(lines, ["Example:", "", "```text", "1. Defaults:", "{", "    \"port\": 1", "}", "```", "", "Done."])
        fenced = to_rustdoc("Run:\n\n```\nlet x = 1;\n```", self.resolve)
        self.assertEqual(fenced, ["Run:", "", "```text", "let x = 1;", "```"])


class NamingTest(unittest.TestCase):
    def test_names(self):
        self.assertEqual(snake("DeviceManager"), "device_manager")
        self.assertEqual(snake("BareboneHostlinkEcamFabric"), "barebone_hostlink_ecam_fabric")
        self.assertEqual(snake("IOStream"), "io_stream")
        self.assertEqual(pascal("server_not_running"), "ServerNotRunning")
        self.assertEqual(pascal("x86_64"), "X86_64".replace("_", ""))

    def test_the_cores_naming_is_used(self):
        from frida_bindgen_core.naming import to_pascal_case, to_snake_case

        for name in ("DeviceManager", "IOStream", "BareboneHostlinkEcamFabric", "Ipv4Address", "DBus"):
            self.assertEqual(snake(name), to_snake_case(name), name)
        for name in ("server_not_running", "x86_64", "gentle"):
            self.assertEqual(pascal(name), to_pascal_case(name), name)

    def test_names_the_core_never_returns_on(self):
        # The core's to_snake_case loops for ever on these; frida-rust's own rule takes them.
        self.assertEqual(snake("X86Thing"), "x86_thing")
        self.assertEqual(snake("A1"), "a1")
        self.assertEqual(snake("ARM64Config"), "arm64_config")

    def test_what_the_cores_pascal_case_does_not_do(self):
        self.assertEqual(pascal("server-not-running"), "ServerNotRunning")
        self.assertEqual(pascal("64bit"), "V64bit")


